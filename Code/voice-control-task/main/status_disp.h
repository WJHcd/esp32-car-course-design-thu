#pragma once

/* ============================================================
 * 状态屏（默认屏幕所有者）
 *
 * 把当前状态实时写到 TFT：模式 / 提示 / 麦克风、BLE、电机状态 /
 * 最近语音动作回显。
 *
 * 屏幕占用规则：**表情功能(FACE 模式)占用屏幕时状态屏让位**——
 * 进入 FACE 先清屏并停止绘制（给表情模块自绘）；离开 FACE 后
 * 自动恢复状态页。将来表情模块真正上屏时同样遵守此约定。
 * ============================================================ */

/**
 * @brief 初始化并启动状态屏（tft 初始化 + 刷新任务，约 0.4s）
 */
void status_disp_init(void);

/**
 * @brief 记录一条最近动作回显（ASCII，自动大写；覆盖旧值）
 *        语音遥控执行动作时由 app_menu 调用
 */
void status_disp_set_action(const char *ascii_action);
