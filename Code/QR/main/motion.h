#pragma once

/* ============================================================
 * 电机动作接口（本工程只需"原地旋转"与"停"）
 *
 * 三轮 120° 全向底盘，旋转运动学复用 task1 标定：
 *   原地旋转：A(左)、C(右) 同向 + B(后) 反向
 * 速度范围 [-100, 100]；方向符号（正=顺/逆）首次实车需标定。
 * ============================================================ */

/**
 * @brief 初始化电机并上电使能
 */
void motion_init(void);

/**
 * @brief 原地旋转
 * @param speed  -100 ~ +100；0=停止；正负方向见 motion.c 顶部标定说明
 */
void motion_rotate(int speed);

/**
 * @brief 全停（PWM 清零 + 短刹车）
 */
void motion_stop(void);
