#pragma once
#include <stdbool.h>
#include "esp_err.h"

/* ============================================================
 * 攻城槌模式（语音说"攻城槌"进入，"选择功能"退出）
 *
 * 流程：
 *   ① 目标查找：小幅度脉冲自旋，屏幕播"搜索"表情动画 +
 *      循环播放"搜索"音效；识别二维码（场地两个箱子贴码 "1"/"2"，
 *      内容 "1" 为撞击目标）。
 *   ② 撞击：识别到 "1" → 屏幕切"撞击"表情动画 + 撞击音效，
 *      对准二维码缓慢前进；超声波测距判断撞到（距离到达最小值
 *      或短时间不再减小）→ 停 → 后退 → 再次前进，循环撞击。
 *   ③ 目标丢失超过 RAM_LOST_BACK_MS → 回到目标查找。
 *
 * 阶段切换时自动切换 GIF 动画（display_gif_use）与音效
 * （audio_out_play，循环播放）。
 * ============================================================ */

void ram_mode_init(void);

/** @brief 进入攻城槌模式（app_menu 切换时调用；内部使能电机并启动任务流程） */
esp_err_t ram_mode_enter(void);

/** @brief 退出攻城槌模式（刹停、停音效、电机断电） */
void ram_mode_exit(void);

/** @brief 当前是否处于攻城槌模式 */
bool ram_mode_is_active(void);
